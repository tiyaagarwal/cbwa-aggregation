"""Recompute every number the paper derives from the CBWA rule.

    python scripts/reproduce_paper.py            # print the table
    python scripts/reproduce_paper.py --write    # also update results/paper_numbers.md

Exits with status 1 if any value differs from the paper (at the paper's rounding).
"""

from __future__ import annotations

import argparse
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from cbwa import __version__  # noqa: E402
from cbwa.paper import (  # noqa: E402
    HOSPITALS,
    N_TRAIN,
    F1_CBWA_FINAL,
    case7_series,
    checks,
    federation_weights,
    table3,
)


def markdown() -> str:
    rows = checks()
    passed = sum(c.ok for c in rows)
    lines = [
        "# The paper's numbers, recomputed",
        "",
        f"Generated by `python scripts/reproduce_paper.py --write` (cbwa {__version__}). "
        "Each value is recomputed from the CBWA rule and compared with the paper at the paper's rounding.",
        "",
        f"**{passed} of {len(rows)} values match.**",
        "",
        "| Where in the paper | Paper | This code | Match |",
        "|---|---|---|---|",
    ]
    for c in rows:
        lines.append(f"| {c.where} | {c.paper} | {c.computed} | {'yes' if c.ok else '**NO**'} |")

    lines += ["", "## Table 3: four-hospital example (n = 246, 40, 10, 2)", "",
              "| Case | H1 | H2 | H3 | H4 |", "|---|---|---|---|---|"]
    for name, w in table3().items():
        lines.append(f"| {name} | " + " | ".join(f"{x:.3f}" for x in w) + " |")

    no_mom, with_mom = case7_series()
    lines += ["", "## Fig. 2b: weight of H4 in Case 7 (rounds 1-10)", "",
              "| Round | " + " | ".join(str(r) for r in range(1, 11)) + " |",
              "|---|" + "---|" * 10,
              "| Without momentum | " + " | ".join(f"{x:.3f}" for x in no_mom) + " |",
              "| With momentum (m = 0.7) | " + " | ".join(f"{x:.3f}" for x in with_mom) + " |"]

    fedavg, cbwa = federation_weights()
    lines += ["", "## Fig. 8: weights of the 16 training hospitals", "",
              "| Hospital | Training patients | Final validation F1 | FedAvg | CBWA |",
              "|---|---|---|---|---|"]
    for h, n, f, a, b in zip(HOSPITALS, N_TRAIN, F1_CBWA_FINAL, fedavg, cbwa):
        lines.append(f"| {h} | {n} | {f:.3f} | {a:.3f} | {b:.3f} |")
    return "\n".join(lines) + "\n"


def main() -> int:
    ap = argparse.ArgumentParser(description=__doc__.splitlines()[0])
    ap.add_argument("--write", action="store_true", help="update results/paper_numbers.md")
    args = ap.parse_args()

    rows = checks()
    width = max(len(c.where) for c in rows)
    print(f"{'Where in the paper':<{width}}  {'Paper':>7}  {'Code':>14}  Match")
    for c in rows:
        print(f"{c.where:<{width}}  {c.paper:>7}  {c.computed:>14}  {'yes' if c.ok else 'NO'}")
    failed = [c for c in rows if not c.ok]
    print(f"\n{len(rows) - len(failed)} of {len(rows)} values match the paper.")

    if args.write:
        out = ROOT / "results" / "paper_numbers.md"
        out.parent.mkdir(exist_ok=True)
        out.write_text(markdown(), encoding="utf-8")
        print(f"Wrote {out.relative_to(ROOT)}")
    return 1 if failed else 0


if __name__ == "__main__":
    sys.exit(main())
